#!/usr/bin/env node
/**
 * Generate `.pier/types/applets.d.ts` from managed plugin manifests.
 * Safe to run without launching Pier.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(repoRoot, ".pier/types");
const outFile = join(outDir, "applets.d.ts");

function collectManifests() {
  const packagesRoot = join(repoRoot, "packages");
  if (!existsSync(packagesRoot)) {
    return [];
  }
  return readdirSync(packagesRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name.startsWith("plugin-"))
    .map((entry) => join(packagesRoot, entry.name, "plugin.json"))
    .filter(existsSync)
    .map((path) => JSON.parse(readFileSync(path, "utf8")));
}

function propsType(schema) {
  if (!schema || typeof schema !== "object") {
    return "Record<string, unknown>";
  }
  const fields = Object.entries(schema).map(([key, value]) => {
    const optional =
      value && typeof value === "object" && value.optional === true ? "?" : "";
    return `    ${key}${optional}: unknown;`;
  });
  if (fields.length === 0) {
    return "Record<string, unknown>";
  }
  return `{\n${fields.join("\n")}\n  }`;
}

const lines = [
  "/** Generated by scripts/generate-canvas-applet-types.mjs — do not edit. */",
  "",
];

for (const manifest of collectManifests()) {
  const pluginId = manifest.id;
  for (const applet of manifest.applets ?? []) {
    const prefix = `${pluginId}.`;
    const appletId = String(applet.id).startsWith(prefix)
      ? String(applet.id).slice(prefix.length)
      : applet.id;
    const specifier = `@pier-applet/${pluginId}/${appletId}`;
    lines.push(`declare module ${JSON.stringify(specifier)} {`);
    lines.push('  import type { ComponentType } from "react";');
    lines.push(
      `  const Applet: ComponentType<${propsType(applet.propsSchema)}>;`
    );
    lines.push("  export default Applet;");
    lines.push("}");
    lines.push("");
  }
}

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, `${lines.join("\n")}\n`);
console.log(outFile);
