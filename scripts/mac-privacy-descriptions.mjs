/**
 * Simplified-Chinese lproj directories that must carry the same
 * InfoPlist.strings table. Order: modern canonical name first.
 */
export const MAC_INFO_PLIST_STRINGS_LOCALE_DIRS = Object.freeze([
  "zh-Hans.lproj",
  "zh_CN.lproj",
]);

export const MAC_INFO_PLIST_STRINGS_RELATIVE_PATHS = Object.freeze(
  MAC_INFO_PLIST_STRINGS_LOCALE_DIRS.map((dir) => `${dir}/InfoPlist.strings`)
);

function escapeStringsValue(value) {
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}

/**
 * Render an Apple `.strings` table (UTF-8) for InfoPlist localization.
 *
 * @param {Record<string, string>} entries
 */
export function renderInfoPlistStrings(entries) {
  const lines = Object.entries(entries).map(
    ([key, value]) => `"${key}" = "${escapeStringsValue(value)}";`
  );
  return `/* Generated by scripts/mac-privacy-descriptions.mjs --write. Do not edit by hand. */\n${lines.join("\n")}\n`;
}

const isMain =
  process.argv[1] != null &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain && process.argv.includes("--write")) {
  for (const relative of MAC_INFO_PLIST_STRINGS_RELATIVE_PATHS) {
    const target = path.join(process.cwd(), "build", ...relative.split("/"));
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(
      target,
      renderInfoPlistStrings(MAC_FOLDER_USAGE_DESCRIPTIONS_ZH_HANS),
      "utf8"
    );
    console.log(`[mac-privacy-descriptions] wrote ${target}`);
  }
}
